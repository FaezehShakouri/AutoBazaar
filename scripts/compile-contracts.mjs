import solc from 'solc';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
const targets=[['contracts/AutoBazaar.sol','AutoBazaar'],['contracts/test/MockUSDC.sol','MockUSDC'],['contracts/test/MockSmartWallet.sol','MockSmartWallet']];
const sources=Object.fromEntries(targets.map(([file])=>[file,{content:readFileSync(file,'utf8')}]));
const result=JSON.parse(solc.compile(JSON.stringify({language:'Solidity',sources,settings:{optimizer:{enabled:true,runs:200},viaIR:true,evmVersion:'cancun',outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object']}}}}),{import:path=>{try{return {contents:readFileSync(`node_modules/${path}`,'utf8')};}catch{return {error:`Missing import ${path}`};}}}));
for(const error of result.errors||[])console.error(error.formattedMessage);
if(result.errors?.some(error=>error.severity==='error'))process.exit(1);
mkdirSync('contracts/artifacts',{recursive:true});
for(const [file,name] of targets){
  const c=result.contracts[file][name];
  writeFileSync(`contracts/artifacts/${name}.json`,JSON.stringify({compiler:solc.version(),evmVersion:'cancun',abi:c.abi,bytecode:`0x${c.evm.bytecode.object}`,deployedBytecode:`0x${c.evm.deployedBytecode.object}`},null,2)+'\n');
  if(name==='AutoBazaar')writeFileSync('lib/arc-abi.mjs',`// Generated by npm run contracts:build.\nexport const ARC_ABI=${JSON.stringify(c.abi)};\n`);
  console.log(`${name}: ${c.evm.bytecode.object.length/2} deployment bytes`);
}
